let locale = 'pt';

export function setLocale(l) {
  if (messages[l]) locale = l;
}

/** t('key', { n: 2 }) — substitui {n} pelos valores. */
export function t(key, vars = {}) {
  const raw = messages[locale][key] ?? messages.pt[key] ?? key;
  return raw.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

